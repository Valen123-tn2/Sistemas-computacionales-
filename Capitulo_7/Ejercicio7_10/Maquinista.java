package Capitulo_7.Ejercicio7_10;

public class Maquinista {

    public String nombreCompleto;
    public String dni;
    public double sueldo;
    public String rango;

    public Maquinista(String nombre, String dni, double sueldo, String rango) {
        this.nombreCompleto = nombre;
        this.dni = dni;
        this.sueldo = sueldo;
        this.rango = rango;
    }
}